from fpdf import FPDF
import datetime
import os

class MedicalReportPDF(FPDF):
    def header(self):
        self.set_font('Arial', 'B', 15)
        self.set_fill_color(30, 64, 175) # Dark blue
        self.set_text_color(255, 255, 255)
        self.cell(0, 15, '  PneumoScan AI - Diagnostic Report', 0, 1, 'L', fill=True)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by PneumoScan AI', 0, 0, 'C')

def create_report(patient_data, prediction_data, image_path=None):
    pdf = MedicalReportPDF()
    pdf.add_page()
    pdf.set_text_color(0, 0, 0)
    
    # Header Info
    pdf.set_font('Arial', '', 10)
    pdf.cell(0, 5, f"Date: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", 0, 1, 'R')
    pdf.ln(5)
    
    # Patient Information
    pdf.set_font('Arial', 'B', 14)
    pdf.set_text_color(30, 64, 175)
    pdf.cell(0, 10, 'Patient Information', 0, 1)
    pdf.set_draw_color(30, 64, 175)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(5)
    
    pdf.set_font('Arial', '', 12)
    pdf.set_text_color(0, 0, 0)
    pdf.cell(0, 8, f"Name: {patient_data.get('name', 'N/A')}", 0, 1)
    pdf.cell(0, 8, f"Age: {patient_data.get('age', 'N/A')}", 0, 1)
    pdf.cell(0, 8, f"Gender: {patient_data.get('gender', 'N/A')}", 0, 1)
    pdf.ln(5)
    
    # Analysis Results
    pdf.set_font('Arial', 'B', 14)
    pdf.set_text_color(30, 64, 175)
    pdf.cell(0, 10, 'Diagnostic Analysis', 0, 1)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(5)
    
    pdf.set_font('Arial', 'B', 12)
    pdf.set_text_color(0, 0, 0)
    result = prediction_data.get('prediction', 'Unknown')
    color = (220, 38, 38) if result == 'Pneumonia' else (22, 163, 74) # Red vs Green
    pdf.set_text_color(*color)
    pdf.cell(0, 8, f"Result: {result}", 0, 1)
    
    pdf.set_text_color(0, 0, 0)
    pdf.set_font('Arial', '', 12)
    pdf.cell(0, 8, f"Confidence: {prediction_data.get('confidence', 0)*100:.2f}%", 0, 1)
    pdf.cell(0, 8, f"Severity Level: {prediction_data.get('severity', 'None')}", 0, 1)
    pdf.ln(10)
    
    # Recommendations
    pdf.set_font('Arial', 'B', 14)
    pdf.set_text_color(30, 64, 175)
    pdf.cell(0, 10, 'Clinical Recommendations', 0, 1)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(5)
    
    pdf.set_font('Arial', '', 12)
    pdf.set_text_color(0, 0, 0)
    for rec in prediction_data.get('recommendations', []):
        pdf.multi_cell(0, 8, f"- {rec}")
    
    pdf.ln(20)
    pdf.set_font('Arial', 'I', 10)
    pdf.set_text_color(128, 128, 128)
    disclaimer = "Disclaimer: This report is AI-generated for triage purposes. It is NOT a definitive diagnosis. Consult a radiologist."
    pdf.multi_cell(0, 5, disclaimer)
    
    report_filename = f"report_{datetime.datetime.now().strftime('%Y%m%d%H%M%S')}.pdf"
    report_path = os.path.join(os.getcwd(), report_filename)
    pdf.output(report_path, 'F')
    return report_path
